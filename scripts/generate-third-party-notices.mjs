import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const read = path => readFileSync(path, "utf8");
const lock = JSON.parse(read("package-lock.json"));
const reviews = JSON.parse(read("licenses/reviewed-packages.json")).packages;
const sections = [];
const rows = [];
for (const [root, locked] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b))) {
  if (!root || locked.dev || root.startsWith("node_modules/@types/")) continue;
  const pkg = JSON.parse(read(`${root}/package.json`));
  if (pkg.version !== locked.version) throw new Error(`Installed version differs from lockfile: ${root}`);
  const review = reviews[pkg.name];
  if (review) {
    if (pkg.version !== review.version || pkg.license !== review.declaredLicense || pkg.author !== review.author) throw new Error(`License review no longer matches package metadata: ${root}`);
    for (const [path, hash] of Object.entries(review.evidenceFiles || {})) {
      if (createHash("sha256").update(readFileSync(path)).digest("hex") !== hash) throw new Error(`Upstream license evidence changed: ${path}`);
    }
    if (review.suppliedLicenseSha256 && createHash("sha256").update(readFileSync(`${root}/LICENSE`)).digest("hex") !== review.suppliedLicenseSha256) throw new Error(`Supplied license changed; review it again: ${root}`);
  }
  const repository = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url || "";
  const files = readdirSync(root).filter(name => /^(licen[cs]e|copying|notice|copyright)(\.|$)/i.test(name));
  if (pkg.name === "isarray" && !files.length) files.push("README.md");
  if (pkg.name === "pako") files.push("lib/zlib/README");
  let license = pkg.license || "not declared";
  if (pkg.name === "react-reader") license = "ISC in package metadata; Apache-2.0 in supplied LICENSE; both terms retained";
  if (pkg.name === "jszip") license = "MIT option of MIT OR GPL-3.0-or-later";
  rows.push(`| ${pkg.name} | ${pkg.version} | ${license} |`);
  let section = `## ${pkg.name} ${pkg.version}\n\nSource package: \`${root}\`\n\nRepository metadata: ${repository}\n\nDeclared license: ${license}\n\n`;
  if (!files.length && !review) throw new Error(`License text needs review: ${root}`);
  if (review) {
    section += `### Distribution review\n\nAttribution from published author metadata and documented upstream origins: ${review.attribution}\n\n${review.review}\n\nEvidence: ${review.sources.join(", ")}\n\n`;
    section += `Published package metadata:\n\n\`\`\`json\n${JSON.stringify({ name: pkg.name, version: pkg.version, license: pkg.license, author: pkg.author, repository: pkg.repository }, null, 2)}\n\`\`\`\n\n`;
    section += `### Standard reference text: ${review.referenceText}\n\nThe following is the unmodified SPDX license template referenced by the package's declared identifier. Its placeholder copyright line is a template, not a newly invented upstream notice. Author attribution is retained separately above.\n\n\`\`\`text\n${read(review.referenceText).trimEnd()}\n\`\`\`\n\n`;
  }
  for (const file of files) {
    let text = read(`${root}/${file}`);
    if (file === "README.md") {
      const start = text.indexOf("## License");
      if (start < 0) throw new Error(`Missing README license section: ${root}`);
      text = text.slice(start + "## License".length).trim();
    }
    if (pkg.name === "jszip") {
      const end = text.indexOf("GPL version 3");
      if (end < 0) throw new Error("Review the updated JSZip dual-license text before selecting the MIT option.");
      text = text.slice(0, end).trim();
    }
    section += `### Supplied text: ${file}\n\n\`\`\`text\n${text.trimEnd()}\n\`\`\`\n\n`;
  }
  sections.push(section);
}

const header = `# Third-Party Notices

Jarvis Reader's original code is licensed under MIT; third-party code and dictionary data retain their own licenses. This file does not relicense them or certify that all upstream licensing questions are resolved.

Generated by \`npm run licenses:generate\` from the locked runtime dependency tree and installed package license files. Notices for transitive helpers are retained conservatively, including dependencies already embedded in JSZip/localForage browser bundles; some may be tree-shaken. Development-only tools and type declarations are excluded. Original license comments in the runtime bundle are also preserved.

**Distribution review:** MIT declarations for marks-pane, its original marks project, and path-webpack are retained with author attributions and the standard license text. For react-reader 0.20.4, both its declared ISC terms and the supplied Apache-2.0 LICENSE are carried and their redistribution conditions observed; no upstream dual-license choice is asserted. The metadata discrepancy remains disclosed. See licenses/reviewed-packages.json and the entries below. This inventory is not an ownership certification or approval by Obsidian.

| Package | Locked version | License evidence |
| --- | --- | --- |
${rows.join("\n")}

## Optional ECDICT dictionary

Source: https://github.com/skywind3000/ECDICT

ECDICT-derived data is distributed separately as a manually imported dictionary package. Existing bundled installations remain supported. The independent ZIP includes its complete MIT license as LICENSE. The converted data's exact original upstream commit is not recorded; the package manifest identifies our converted content by checksums, not an invented upstream revision.

\`\`\`text
${read("dictionaries/ECDICT-LICENSE").trimEnd()}
\`\`\`

## Node.js path-derived notice

${read("licenses/nodejs-v7-path.txt").trimEnd()}

`;
// Normalize line-ending whitespace only; retain copyright, grants and disclaimers.
const output = (header + sections.join("\n")).split("\n").map(line => line.trimEnd()).join("\n").trimEnd() + "\n";
if (process.argv.includes("--check")) {
  if (read("THIRD_PARTY_NOTICES.md") !== output) throw new Error("Third-party notices are stale. Run npm run licenses:generate and review the diff.");
  console.log(`Third-party notice inventory matches ${rows.length} runtime dependency distributions plus ECDICT and Node.js path notices; pinned distribution reviews match.`);
} else {
  writeFileSync("THIRD_PARTY_NOTICES.md", output);
  console.log(`Generated notices for ${rows.length} runtime dependency distributions with reviewed supplementary texts.`);
}
